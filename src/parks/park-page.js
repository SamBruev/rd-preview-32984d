/* =====================================================================
   ParkPage — базовый класс страницы парка. Плюс реестр этих классов.

   Как разложены обязанности (и почему их четыре, а не одна):

     факты парка    — content.js: адрес, часы, цены, зоны, кадры;
     тексты парка   — словарь T в файле самого парка;
     общие блоки    — каркас parkBase из pages.js: герой, строка адреса
                      и цен, состав зон, переход в соседний парк;
     порядок блоков — этот класс.

   SRP. Класс отвечает ровно за одно: за состав и порядок блоков на
   странице парка. Он не хранит фактов, не рисует разметку общих блоков
   и не знает текущего языка — за каждым ответом он ходит к тому, чья
   это работа. Поэтому и правится он только тогда, когда меняется
   порядок блоков, а не когда переехал парк или подорожало занятие.

   Инверсия зависимостей. В классе не упомянут ни один парк. В render()
   ему передают запись парка p — абстракцию «данные парка из content.js»
   — и каркас frame — абстракцию «как рисуются общие блоки». База знает
   только их интерфейс: у p есть zones и photo, у frame есть hero, meta,
   zones и next. Переедет содержимое или перерисуется каркас — этот файл
   останется прежним.

   Наследование сделано конструктором и прототипом, без class: сайт
   открывают старые WebView, а через них проходит заметная доля заходов
   из мессенджеров.
   ===================================================================== */
(function (root) {
  'use strict';

  /* config:
       slug     — ключ парка в content.js;
       texts    — { ru: {...}, en: {...} }, словарь самого парка;
       card     — короткая копия парка для карточки на главной;
       nextSlug — парк, в который уводит нижний блок страницы. */
  function ParkPage(config) {
    this.slug = config.slug;
    this.texts = config.texts;
    this.card = config.card;
    this.nextSlug = config.nextSlug;
  }

  /* Словарь на текущем языке. Язык спрашиваем у приложения при каждой
     отрисовке, а не запоминаем в поле: переключатель языка перерисовывает
     страницу тем же экземпляром. */
  ParkPage.prototype.text = function (h) { return this.texts[h.L()]; };

  /* ---------------------- ШАБЛОННЫЙ МЕТОД ----------------------
     Порядок блоков задан здесь один раз и для всех трёх парков:
     герой → адрес, часы и цены → свои секции → переход в соседний парк.
     Наследник не переписывает render() — он переопределяет шаги.
     Так парк не может случайно потерять адрес или уехать в никуда. */
  ParkPage.prototype.render = function (h, p, frame) {
    return this.hero(h, p, frame) +
      this.switcher(h, p) +
      this.meta(h, p, frame) +
      this.sections(h, p, frame) +
      this.next(h, p, frame);
  };

  /* Переключатель парков — сразу под героем на каждой странице парка.
     Требование владельца 19.08.2026: из любого парка в любой другой
     одним тапом, без «назад» и захода через главную. Метод базы, а не
     наследников: появившись здесь, он появился на всех трёх страницах
     сразу и не может разъехаться. Текущий парк показан не ссылкой,
     а меткой — человек видит, где он. */
  ParkPage.prototype.switcher = function (h, p) {
    const esc = h.esc, P = h.P;
    return '<nav class="pk-switch" aria-label="' +
      esc(h.L() === 'ru' ? 'Другие парки сети' : 'Other parks') + '">' +
      '<div class="shell pk-switch__in">' +
      '<span class="mono">' + esc(h.L() === 'ru' ? 'Парки сети' : 'The parks') + '</span>' +
      h.parks().map(function (x) {
        if (x.slug === p.slug) {
          return '<span class="pk-switch__now" aria-current="page">' + esc(P(x.short)) + '</span>';
        }
        return '<a class="pk-switch__a" href="' + h.href('park', x.slug) + '">' +
          esc(P(x.short)) + ' <span aria-hidden="true">→</span></a>';
      }).join('') +
      '</div></nav>';
  };

  /* Герой: кадр парка во всю ширину, заголовок и лид. Парку, у которого
     своя шапка (свой кадр, другая пропорция), достаточно переопределить
     этот шаг — остальные три останутся общими. */
  ParkPage.prototype.hero = function (h, p, frame) {
    const t = this.text(h);
    return frame.hero(h, p, t.kicker, t.title, t.lead);
  };

  /* Адрес, часы, телефон, цены, кнопка записи и тёмный блок «как найти
     вход». Заголовок тёмного блока берётся из словаря парка. */
  ParkPage.prototype.meta = function (h, p, frame) {
    return frame.meta(h, p, this.text(h).findTitle);
  };

  /* ХУК ПОД СВОИ СЕКЦИИ. База пуста намеренно: она не знает и не должна
     знать, что у одного парка три дорожки под три уровня, а у другого
     пять шагов первого визита. Отсюда же наследник зовёт zones(): состав
     парка у всех троих стоит на разной высоте страницы. */
  ParkPage.prototype.sections = function (h, p, frame) { return ''; };

  /* Состав и размеры зон — общий блок поверх данных из content.js. */
  ParkPage.prototype.zones = function (h, p, frame) {
    /* Четвёртым параметром — вводная фраза секции, если парк её задал
       в content.js (zonesLead). У Сокольников это строка владельца. */
    return frame.zones(h, p, this.text(h).zonesTitle, p.zonesLead);
  };

  /* Маршрут внутри сети: куда ехать дальше, когда этот парк перерос. */
  ParkPage.prototype.next = function (h, p, frame) {
    const t = this.text(h);
    return frame.next(h, this.nextSlug, t.nextText, t.nextCta);
  };

  /* =====================================================================
     Реестр страниц парков.

     Open/Closed. Диспетчер в pages.js не разбирает слаги через if-else и
     вообще не знает названий парков: он спрашивает реестр. Новый парк —
     новый файл с наследником и одна строка register() в конце этого
     файла. Ни база, ни реестр, ни диспетчер при этом не правятся.

     Подстановка Лисков. Реестр хранит наследников как ParkPage и ничего
     сверх базового договора о них не знает: у каждого есть slug, card и
     render(h, p, frame). Поэтому для роутера три парка взаимозаменяемы —
     он не проверяет, кто именно ему достался, и не может ошибиться в
     проверке, которой нет.
     ===================================================================== */
  function ParkRegistry() {
    /* Один список на весь слой парков, в порядке подключения файлов.
       Экземпляр каждого класса создаётся один раз при регистрации:
       страница парка ничего не помнит между отрисовками, поэтому
       заводить её заново на каждый переход незачем. */
    this.pages = [];
  }

  ParkRegistry.prototype.register = function (ParkClass) {
    const page = new ParkClass();
    this.pages.push(page);
    /* Витрина для главной: home.js и app.js берут короткую копию парка
       как root.RDPark[slug].card. Реестр держит её сам — файлам парков
       не нужно знать ни про этого потребителя, ни про имя переменной. */
    root.RDPark[page.slug] = page;
    return page;
  };

  /* Диспетчер просит страницу по слагу — реестр идёт по списку и отдаёт
     ту, что назвала этот слаг своим. Ни одного if по имени парка. */
  ParkRegistry.prototype.find = function (slug) {
    for (let i = 0; i < this.pages.length; i++) {
      if (this.pages[i].slug === slug) return this.pages[i];
    }
    return null;
  };

  root.RDPark = root.RDPark || {};   // slug → экземпляр, витрина для главной
  root.RDParkPage = ParkPage;        // база, от которой наследуются парки
  root.RDParks = new ParkRegistry(); // реестр, к которому ходит диспетчер
})(typeof window !== 'undefined' ? window : this);
